"""`/lanes:init` — set up everything `/lanes:doctor` checks, in one run.

Writes `.claude/lanes/config.toml` and the three extension-point stubs; creates the backlog
folder with a README and a `.gitignore` for its two generated views; declares the plugin in
`.claude/settings.json` from this machine's marketplace record; installs the view hooks and the
commit guard (LANES-52). Writes nothing that already exists unless `--force` is given, never
overwrites `.claude/settings.json` (it only adds lanes to it), and says which files it wrote,
updated and left alone. The config it writes is the solo-mode template with the installed
plugin version pinned in `plugin_version`, so `/lanes:doctor` can detect drift from day one.

The commit guard is held back while a file init wrote is uncommitted and outside
`git.main_direct_paths`: installed first, it would refuse the very commit init asks for.
A second run after that commit installs it.

Usage:
    python3 lanes_init.py [--root PATH] [--force] [--projects CORE,INFRA,DOC]
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _console import use_utf8_console  # noqa: E402
import lanes_config as lc              # noqa: E402
import lanes_doctor as ld              # noqa: E402  (init writes what the doctor reads)
import guard_commit as gc              # noqa: E402
import guard_position as gp            # noqa: E402
import view_hooks as vh                # noqa: E402

_PROJECT_RE = re.compile(r"^[A-Z][A-Z0-9]*$")
VIEWS = ("INDEX.md", "index.html")
VIEWS_IGNORE_HEADER = ("# Generated by lanes (backlog_index.py): local views, rewritten by every backlog\n"
                       "# write. Never commit them.\n")


def render_config(template: str, version: str, projects: list) -> str:
    quoted = ", ".join(f'"{p}"' for p in projects)
    return template.replace("{{PLUGIN_VERSION}}", version).replace("{{PROJECTS}}", quoted)


def parse_projects(text: str | None) -> list:
    if not text:
        return list(lc.DEFAULTS["backlog"]["projects"])
    projects = [p.strip().upper() for p in text.split(",") if p.strip()]
    bad = [p for p in projects if not _PROJECT_RE.match(p)]
    if bad:
        raise SystemExit(f"--projects: {bad!r} must match [A-Z][A-Z0-9]* (IDs read as PREFIX-N)")
    if not projects:
        raise SystemExit("--projects: no prefixes given")
    return projects


def is_ignored(root: Path, rel: str) -> bool:
    try:
        done = subprocess.run(["git", "check-ignore", "-q", "--", rel], cwd=root,
                              capture_output=True, timeout=10)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return done.returncode == 0


def marketplace_source(root: Path) -> tuple[Optional[str], object]:
    """(marketplace, its registered source) this machine installed lanes from, or (None, why not).

    The marketplace is the one this plugin's cache path names (`<plugins>/cache/<mkt>/lanes/<v>`),
    else the only one `installed_plugins.json` lists lanes under; the source is copied from
    `known_marketplaces.json`, which is exactly what the doctor's `marketplace` line compares."""
    plugin = lc.plugin_root()
    if len(plugin.parents) > 3 and plugin.parents[2].name == "cache":
        mkt = plugin.parents[1].name
    else:
        mkts = sorted({k.partition("@")[2] for k, _r in ld.lanes_installs(root)} - {""})
        if len(mkts) != 1:
            return None, ("lanes is not installed from a marketplace on this machine (a --plugin-dir "
                          "checkout?)" if not mkts else f"lanes is installed from {len(mkts)} marketplaces ("
                          + ", ".join(mkts) + ")")
        mkt = mkts[0]
    known = ld._load_json(ld.plugins_dir() / "known_marketplaces.json")
    entry = known.get(mkt) if isinstance(known, dict) else None
    source = entry.get("source") if isinstance(entry, dict) else None
    if not isinstance(source, dict):
        return None, f"marketplace `{mkt}` has no registered source on this machine"
    return mkt, dict(source)


def declare_plugin(root: Path, out: dict) -> None:
    """Add lanes to `.claude/settings.json` so the next person is prompted to install it. Only
    adds: an existing file's other keys stay, a lanes entry already there is kept, and an
    explicit `false` for lanes is the owner's choice and is left alone."""
    rel = ld.SETTINGS_REL
    path = root / rel
    by_hand = "declare it by hand (README → Install)"
    data: object = {}
    if path.exists():
        data = ld._load_json(path)
        if not isinstance(data, dict):
            out["warnings"].append(f"{rel} is not a JSON object; lanes left it alone -- {by_hand}")
            return
        if ld._lanes_problem(data) is None:
            out["kept"].append(rel)
            return
    mkt, source = marketplace_source(root)
    if mkt is None:
        out["warnings"].append(f"{rel}: lanes not declared -- {source}; {by_hand}")
        return
    known = data.setdefault("extraKnownMarketplaces", {})
    enabled = data.setdefault("enabledPlugins", {})
    if not isinstance(known, dict) or not isinstance(enabled, dict):
        out["warnings"].append(f"{rel}: extraKnownMarketplaces or enabledPlugins is not an object; "
                               f"lanes left the file alone -- {by_hand}")
        return
    key = f"lanes@{mkt}"
    if enabled.get(key) is False:
        out["warnings"].append(f"{rel} sets `{key}` to false; lanes left it alone")
        return
    if ld._declared_source(data, mkt) is None:
        known[mkt] = {**(known.get(mkt) if isinstance(known.get(mkt), dict) else {}), "source": source}
    enabled[key] = True
    existed = path.exists()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8", newline="\n")
    out["updated" if existed else "wrote"].append(rel)


def ignore_views(root: Path, backlog_rel: str, out: dict) -> None:
    """Gitignore the two generated views with a `.gitignore` inside the backlog folder: it moves
    with the folder, and it sits under the main-direct `docs/` where the root one does not."""
    missing = [v for v in VIEWS if not is_ignored(root, f"{backlog_rel}/{v}")]
    if not missing:
        return
    rel = f"{backlog_rel}/.gitignore"
    path = root / rel
    existed = path.exists()
    text = path.read_text(encoding="utf-8") if existed else VIEWS_IGNORE_HEADER
    if text and not text.endswith("\n"):
        text += "\n"
    path.write_text(text + "".join(f"{v}\n" for v in missing), encoding="utf-8", newline="\n")
    out["updated" if existed else "wrote"].append(rel)


def scaffold(root: Path, force: bool, projects: list, templates: Path | None = None) -> dict:
    """Write the files. Returns {"wrote": [...], "updated": [...], "kept": [...], "warnings": [...]}."""
    templates = templates or (lc.plugin_root() / "templates")
    lanes_dir = root / lc.LANES_DIR_REL
    lanes_dir.mkdir(parents=True, exist_ok=True)
    version = lc.installed_version() or "0.0.0"
    out = {"wrote": [], "updated": [], "kept": [], "warnings": []}

    def put(target: Path, content: str):
        rel = target.relative_to(root).as_posix()
        if target.exists() and not force:
            out["kept"].append(rel)
            return
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
        out["wrote"].append(rel)

    put(lanes_dir / "config.toml",
        render_config((templates / "config.toml").read_text(encoding="utf-8"), version, projects))
    for stub in lc.EXTENSION_FILES:
        put(lanes_dir / stub, (templates / stub).read_text(encoding="utf-8"))

    loaded = lc.load(root=root)
    backlog_rel = lc.resolve(loaded.raw)["backlog_dir"].strip("/")
    put(root / backlog_rel / "README.md", (templates / "backlog-README.md").read_text(encoding="utf-8"))
    ignore_views(root, backlog_rel, out)
    declare_plugin(root, out)

    if is_ignored(root, lc.CONFIG_REL):
        out["warnings"].append(
            f"{lc.CONFIG_REL} is gitignored in this repo. The config must be TRACKED: every operator "
            f"and machine reads the same file from git. If the rule is `.claude/`, change it to `.claude/*` "
            f"and add `!.claude/settings.json` and `!.claude/lanes/` -- git cannot re-include a file whose "
            f"parent directory is excluded."
        )
    for p in loaded.errors:
        out["warnings"].append(f"the written config fails validation: {p.message}")
    return out


def uncommitted(root: Path, paths: list) -> list:
    """The paths among `paths` that are untracked or differ from HEAD."""
    if not paths:
        return []
    try:
        done = subprocess.run(["git", "status", "--porcelain", "-z", "--untracked-files=all", "--", *paths],
                              cwd=root, capture_output=True, text=True, encoding="utf-8", timeout=15)
    except (OSError, subprocess.TimeoutExpired):
        return list(paths)
    return sorted({e[3:] for e in done.stdout.split("\0") if len(e) > 3} & set(paths))


def install_hooks(root: Path, managed: list) -> tuple[list, list]:
    """Install the view hooks and the commit guard. Returns (lines to print, the paths that held
    the guard back). The guard waits while a file init manages is uncommitted and outside
    `git.main_direct_paths`, because installed now it would refuse committing that file on the
    main branch -- the commit init asks for."""
    try:
        w = gc.where(str(root))
    except gp.GitUnavailable as exc:
        return [f"hooks: not installed -- git could not run ({exc})"], []
    if w is None:
        return ["hooks: not installed -- cannot read the repository's position"], []
    lines = [vh.install(w.main_clone)[1]]
    rules = gp.rules_for(w.main_clone, env={})
    waiting = [p for p in uncommitted(root, managed) if not gp.is_main_direct(p, rules.main_direct)]
    if waiting and gc.status(w.main_clone)[0] == "absent":
        lines.append(f"commit guard: held back -- it refuses a commit on `{rules.main_branch}` of "
                     f"{', '.join(waiting)} (outside git.main_direct_paths); commit, then run /lanes:init again")
        return lines, waiting
    lines.append(gc.install(w.main_clone)[1])
    return lines, []


def main(argv=None) -> int:
    use_utf8_console()
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", help="repository to initialize (default: the one containing the cwd)")
    ap.add_argument("--force", action="store_true", help="overwrite files that already exist "
                                                         "(never .claude/settings.json, which init only adds to)")
    ap.add_argument("--projects", help="comma-separated issue ID prefixes, e.g. CORE,INFRA,DOC")
    args = ap.parse_args(argv)

    root = lc.repo_root(cwd=args.root) if args.root else lc.repo_root()
    if root is None:
        print("lanes init: not inside a git repository (the config is tracked, so it needs one)", file=sys.stderr)
        return 1
    projects = parse_projects(args.projects)
    result = scaffold(root, args.force, projects)
    managed = result["wrote"] + result["updated"] + result["kept"]
    hook_lines, waiting = install_hooks(root, managed)

    for verb in ("wrote", "updated"):
        for rel in result[verb]:
            print(f"{verb:<6} {rel}")
    for rel in result["kept"]:
        print(f"kept   {rel}  (exists; --force overwrites)" if rel != ld.SETTINGS_REL
              else f"kept   {rel}  (already declares lanes)")
    for line in hook_lines:
        print(f"hooks  {line}")
    for w in result["warnings"]:
        print(f"WARN   {w}")
    cfg = lc.resolve(lc.load(root=root).raw)
    print()
    print(f"mode: {lc.describe_mode(cfg)}")
    print(f"projects: {', '.join(cfg['projects'])}   main branch: {cfg['main_branch']}   tests: {cfg['test_command']}")
    print()
    print("next: review .claude/lanes/config.toml (main_branch, tests.command, main_direct_paths),")
    print("      fill [[operators]] only if more than one person or machine works this repo,")
    pending = uncommitted(root, managed)
    if pending:
        print("      commit what init wrote:")
        print(f"          git add -- {' '.join(pending)}")
        print('          git commit -m "Adopt lanes"')
    if waiting:
        print("      run /lanes:init once more to install the commit guard it held back,")
    print("      then run /lanes:doctor.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
