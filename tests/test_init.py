def test_init_commit_init_and_the_doctor_reads_zero_warn(repo, monkeypatch, tmp_path, capsys):
    """The acceptance walk: a fresh repo, /lanes:init, the commit it prints, /lanes:init again
    for the guard it held back, and every doctor line is OK or SKIP -- and still is after the
    first issue is minted and committed on main through the guard."""
    _machine(monkeypatch, tmp_path)
    assert li.main(["--root", str(repo)]) == 0
    out = capsys.readouterr().out
    add = next(line for line in out.splitlines() if "git add -- " in line).split("git add -- ", 1)[1].split()
    assert sorted(add) == sorted(LANES_FILES + [README, IGNORE, SETTINGS])
    assert "run /lanes:init once more" in out
    git("add", "--", *add, cwd=repo)
    git("commit", "-q", "-m", "Adopt lanes", cwd=repo)

    assert li.main(["--root", str(repo)]) == 0
    out = capsys.readouterr().out
    assert "hooks  commit guard: installed" in out and "git add" not in out and "once more" not in out

    def loud():
        return [(c.label, c.status, c.detail) for c in ld.run(repo) if c.status in (ld.WARN, ld.FAIL)]
    assert loud() == []

    subprocess.run([sys.executable, str(SCRIPTS / "backlog_new.py"), "CORE", "first issue", "--reported-by=claude",
                    "--no-fetch"], cwd=repo, check=True, capture_output=True)
    assert li.uncommitted(repo, [IGNORE, README]) == [], "the generated views stay out of git"
    git("add", "docs/backlog/CORE", cwd=repo)
    git("commit", "-q", "-m", "open CORE-1", cwd=repo)
    assert loud() == []
