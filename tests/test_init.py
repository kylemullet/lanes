def _managed(out):
    return out["wrote"] + out["updated"] + out["kept"]


def test_the_guard_waits_for_the_commit_it_would_refuse(repo, monkeypatch, tmp_path):
    _machine(monkeypatch, tmp_path)
    out = li.scaffold(repo, force=False, projects=["CORE"])
    lines, waiting = li.install_hooks(repo, _managed(out))
    assert waiting == [SETTINGS] and "held back" in lines[-1] and SETTINGS in lines[-1]
    assert gc.status(str(repo))[0] == "absent"
    assert vh.status(str(repo))[0] == "installed", "the view hooks refuse nothing, so they go in at once"
    git("add", "--", *li.uncommitted(repo, _managed(out)), cwd=repo)
    git("commit", "-q", "-m", "Adopt lanes", cwd=repo)
    lines, waiting = li.install_hooks(repo, _managed(li.scaffold(repo, force=False, projects=["CORE"])))
    assert waiting == [] and gc.status(str(repo))[0] == "installed"


def test_the_guard_goes_in_at_once_when_everything_init_wrote_is_main_direct(repo):
    out = li.scaffold(repo, force=False, projects=["CORE"])               # no settings.json: no marketplace
    lines, waiting = li.install_hooks(repo, _managed(out))
