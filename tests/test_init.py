LANES_FILES = [".claude/lanes/config.toml", ".claude/lanes/preflight.md",
               ".claude/lanes/lane-setup.md", ".claude/lanes/pre-land.md"]
README, IGNORE, SETTINGS = "docs/backlog/README.md", "docs/backlog/.gitignore", ".claude/settings.json"
SOURCE = {"source": "github", "repo": "o/lanes", "ref": "next"}


def _machine(monkeypatch, tmp_path, source=SOURCE, mkt="lanes-marketplace"):
    """A fake ~/.claude/plugins: lanes installed (user scope) from `mkt`, at its marketplace clone's tip."""
    plugins = tmp_path / "plugins-dir"
    plugins.mkdir()
    monkeypatch.setenv("LANES_PLUGINS_DIR", str(plugins))
    clone = tmp_path / "mkt-clone"
    clone.mkdir()
    git("init", "-q", cwd=clone)
    git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", "x", cwd=clone)
    tip = git("rev-parse", "HEAD", cwd=clone)
    (plugins / "known_marketplaces.json").write_text(
        json.dumps({mkt: {"source": source, "installLocation": str(clone)}}), encoding="utf-8")
    (plugins / "installed_plugins.json").write_text(json.dumps({"version": 2, "plugins": {
        f"lanes@{mkt}": [{"scope": "user", "version": lc.installed_version(), "gitCommitSha": tip}]}}),
        encoding="utf-8")
    return plugins


def test_scaffold_writes_then_keeps_then_forces(repo):
    first = li.scaffold(repo, force=False, projects=["CORE", "INFRA"])
    assert sorted(first["wrote"]) == sorted(LANES_FILES + [README, IGNORE])
    assert first["kept"] == [] and first["updated"] == []
    # no marketplace on this (fake) machine, so there is no source to declare -- said, not guessed
    assert len(first["warnings"]) == 1 and f"{SETTINGS}: lanes not declared" in first["warnings"][0]
    assert not (repo / SETTINGS).exists()
    cfg_text = (repo / lc.CONFIG_REL).read_text(encoding="utf-8")
    assert f'plugin_version = "{lc.installed_version()}"' in cfg_text
    assert 'projects = ["CORE", "INFRA"]' in cfg_text
    assert "{{" not in cfg_text

    loaded = lc.load(root=repo)
    assert loaded.found and loaded.problems == []
    cfg = lc.resolve(loaded.raw, user_name="Tester", platform="linux")
    assert cfg["solo"] and cfg["projects"] == ["CORE", "INFRA"]

    (repo / lc.CONFIG_REL).write_text("# edited by hand\n", encoding="utf-8")
    second = li.scaffold(repo, force=False, projects=["CORE"])
    assert second["wrote"] == [] and second["updated"] == []
    assert sorted(second["kept"]) == sorted(LANES_FILES + [README])
    assert (repo / lc.CONFIG_REL).read_text(encoding="utf-8") == "# edited by hand\n"

    third = li.scaffold(repo, force=True, projects=["CORE"])
    assert sorted(third["wrote"]) == sorted(LANES_FILES + [README])     # the views are ignored already
    assert 'projects = ["CORE"]' in (repo / lc.CONFIG_REL).read_text(encoding="utf-8")


